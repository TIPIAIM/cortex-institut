const unique = (values) => [...new Set(values.filter(Boolean))];

export const getCatalogueById = (id) =>
  catalogues.find((catalogue) => catalogue.id === id) || catalogues[0];

export const getSchoolPrograms = (school) => {
  if (!school) return [];

  const blockPrograms = (school.blocks || []).flatMap((block) => {
    if (block.programs?.length) {
      return block.programs.map((program) => program.title);
    }
    return [];
  });

  return unique([...(school.pathways || []), ...blockPrograms]);
};

export const getSchoolSearchText = (school) => {
  const blockText = (school.blocks || []).flatMap((block) => [
    block.title,
    ...(block.modules || []),
    ...(block.programs || []).flatMap((program) => [
      program.title,
      program.duration,
      ...(program.modules || []),
      ...(program.sections || []).flatMap((section) => [
        section.title,
        ...(section.modules || []),
      ]),
    ]),
  ]);

  return [
    school.title,
    school.schoolName,
    school.summary,
    school.duration,
    ...(school.pathways || []),
    ...(school.qualificationLevels || []).flatMap((level) => [
      level.title,
      level.duration,
      level.description,
    ]),
    ...blockText,
  ]
    .filter(Boolean)
    .join(" ")
    .toLocaleLowerCase("fr");
};

/**
 * Export de compatibilité avec la navigation existante.
 * Il ne contient plus les anciens programmes : les intitulés sont agrégés
 * uniquement depuis les trois nouveaux catalogues.
 */
export const filieres = SCHOOL_META.map((meta) => {
  const variants = catalogues
    .flatMap((catalogue) => catalogue.schools || [])
    .filter((school) => school.slug === meta.slug);

  return {
    slug: meta.slug,
    title: meta.title,
    iconName: meta.iconName,
    description: variants.find((school) => school.summary)?.summary || "",
    programs: unique(variants.flatMap(getSchoolPrograms)),
    keywords: unique(
      variants.flatMap((school) =>
        getSchoolSearchText(school)
          .split(/\s+/)
          .filter((word) => word.length > 3)
      )
    ),
    programCards: [],
  };
});

export const catalogueIds = catalogues.map((catalogue) => catalogue.id);

/** Helpers dérivés des catalogues officiels pour les composants UI/SEO. */
export const getCatalogueSchools = (catalogue) => [
  ...(catalogue?.schools || []),
  ...(catalogue?.additionalOffers || []),
];

export const getSchoolProgrammeCount = (school) => {
  const blockProgrammes = (school?.blocks || []).reduce(
    (sum, block) => sum + (block.programs?.length || 0),
    0
  );

  return blockProgrammes || school?.pathways?.length || 0;
};

export const getCatalogueKeywords = (catalogue) =>
  unique(
    getCatalogueSchools(catalogue).flatMap((school) => [
      school.title,
      school.schoolName,
      ...(school.blocks || []).map((block) => block.title),
      ...getSchoolPrograms(school),
    ])
  );

